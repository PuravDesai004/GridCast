-- USER-RUN ONLY in SnowSQL or a supported client. Replace <ABS_EXPORT_DIR>.
-- Load sample_versions.parquet first. Validate against the local export manifest before the full file.
USE WAREHOUSE GRIDCAST_WH;
ALTER SESSION SET TIMEZONE='UTC',QUERY_TAG='GridCast_manual_load',STATEMENT_TIMEOUT_IN_SECONDS=300;
PUT 'file://<ABS_EXPORT_DIR>/sample_versions.parquet' @GRIDCAST_PILOT.RAW.INPUT_STAGE/sample AUTO_COMPRESS=FALSE;
TRUNCATE TABLE GRIDCAST_PILOT.RAW.VERSION_STAGE;
COPY INTO GRIDCAST_PILOT.RAW.VERSION_STAGE FROM
  (SELECT $1 FROM @GRIDCAST_PILOT.RAW.INPUT_STAGE/sample/)
  FILE_FORMAT=(FORMAT_NAME='GRIDCAST_PILOT.RAW.PARQUET_FMT');
-- Gate: these queries must return zero rows before MERGE.
SELECT PAYLOAD:version_id::VARCHAR FROM GRIDCAST_PILOT.RAW.VERSION_STAGE
 GROUP BY 1 HAVING COUNT(DISTINCT TO_JSON(PAYLOAD))>1;
SELECT * FROM GRIDCAST_PILOT.RAW.VERSION_STAGE WHERE PAYLOAD:authority::VARCHAR!='PJM'
 OR PAYLOAD:metric::VARCHAR!='D' OR PAYLOAD:unit::VARCHAR!='megawatthours'
 OR TRY_TO_TIMESTAMP_TZ(PAYLOAD:observation_time::VARCHAR) IS NULL;
MERGE INTO GRIDCAST_PILOT.RAW.OBSERVATION_VERSION target USING (
 SELECT PAYLOAD:version_id::VARCHAR VERSION_ID,PAYLOAD:authority::VARCHAR AUTHORITY,
 PAYLOAD:metric::VARCHAR METRIC,TO_TIMESTAMP_TZ(PAYLOAD:observation_time::VARCHAR) OBSERVATION_TIME,
 PAYLOAD:raw_value::VARCHAR RAW_VALUE,PAYLOAD:value::DOUBLE VALUE,PAYLOAD:unit::VARCHAR UNIT,
 TO_TIMESTAMP_TZ(PAYLOAD:first_seen::VARCHAR) FIRST_SEEN,PAYLOAD:valid::BOOLEAN VALID,
 PAYLOAD:quality::VARCHAR QUALITY FROM GRIDCAST_PILOT.RAW.VERSION_STAGE
 QUALIFY ROW_NUMBER() OVER(PARTITION BY PAYLOAD:version_id ORDER BY TO_JSON(PAYLOAD))=1
) source ON target.VERSION_ID=source.VERSION_ID WHEN NOT MATCHED THEN INSERT ALL BY NAME;
SELECT COUNT(*),COUNT(DISTINCT VERSION_ID),MIN(OBSERVATION_TIME),MAX(OBSERVATION_TIME),COUNT_IF(NOT VALID)
 FROM GRIDCAST_PILOT.RAW.OBSERVATION_VERSION;
-- Repeat sample COPY/MERGE; observation_version row count must not increase.
-- Then switch only the input path to observation_versions.parquet under /full_versions.
PUT 'file://<ABS_EXPORT_DIR>/observation_versions.parquet' @GRIDCAST_PILOT.RAW.INPUT_STAGE/full_versions AUTO_COMPRESS=FALSE;
-- User repeats VERSION_STAGE COPY and the same MERGE against /full_versions/ after sample acceptance.
PUT 'file://<ABS_EXPORT_DIR>/observation_receipts.parquet' @GRIDCAST_PILOT.RAW.INPUT_STAGE/receipts AUTO_COMPRESS=FALSE;
TRUNCATE TABLE GRIDCAST_PILOT.RAW.RECEIPT_STAGE;
COPY INTO GRIDCAST_PILOT.RAW.RECEIPT_STAGE FROM
 (SELECT $1 FROM @GRIDCAST_PILOT.RAW.INPUT_STAGE/receipts/)
 FILE_FORMAT=(FORMAT_NAME='GRIDCAST_PILOT.RAW.PARQUET_FMT');
SELECT PAYLOAD:fetch_id::VARCHAR,PAYLOAD:version_id::VARCHAR
 FROM GRIDCAST_PILOT.RAW.RECEIPT_STAGE GROUP BY 1,2 HAVING COUNT(DISTINCT TO_JSON(PAYLOAD))>1;
MERGE INTO GRIDCAST_PILOT.RAW.OBSERVATION_RECEIPT target USING (
 SELECT PAYLOAD:fetch_id::VARCHAR FETCH_ID,PAYLOAD:version_id::VARCHAR VERSION_ID,
 PAYLOAD:artifact_id::VARCHAR ARTIFACT_ID,PAYLOAD:page_offset::BIGINT PAGE_OFFSET,
 PAYLOAD:row_number::BIGINT ROW_NUMBER,TO_TIMESTAMP_TZ(PAYLOAD:fetched_at::VARCHAR) FETCHED_AT,
 PAYLOAD:delivery_order::BIGINT DELIVERY_ORDER FROM GRIDCAST_PILOT.RAW.RECEIPT_STAGE
 QUALIFY ROW_NUMBER() OVER(PARTITION BY PAYLOAD:fetch_id,PAYLOAD:version_id ORDER BY TO_JSON(PAYLOAD))=1
) source ON target.FETCH_ID=source.FETCH_ID AND target.VERSION_ID=source.VERSION_ID
WHEN NOT MATCHED THEN INSERT ALL BY NAME;
SELECT COUNT(*),COUNT(DISTINCT FETCH_ID),MIN(FETCHED_AT),MAX(FETCHED_AT) FROM GRIDCAST_PILOT.RAW.OBSERVATION_RECEIPT;
-- Standard table uniqueness constraints are not used as enforcement.
ALTER WAREHOUSE GRIDCAST_WH SUSPEND;

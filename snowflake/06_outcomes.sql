-- USER-RUN ONLY. Retrospective frozen source: use the exact exported collection cutoff.
USE WAREHOUSE GRIDCAST_WH;
ALTER SESSION SET TIMEZONE='UTC',QUERY_TAG='GridCast_manual_outcomes',STATEMENT_TIMEOUT_IN_SECONDS=300;
SET snapshot_cutoff='<EXPORTED_SNAPSHOT_CUTOFF_UTC>';
CREATE OR REPLACE TEMPORARY TABLE GRIDCAST_PILOT.ANALYTICS.ERROR_LOAD AS
WITH actuals AS (
 SELECT v.* FROM GRIDCAST_PILOT.RAW.OBSERVATION_VERSION v
 JOIN GRIDCAST_PILOT.RAW.OBSERVATION_RECEIPT r USING(VERSION_ID)
 WHERE VALID AND r.FETCHED_AT<=TO_TIMESTAMP_TZ($snapshot_cutoff)
 QUALIFY ROW_NUMBER() OVER(PARTITION BY AUTHORITY,METRIC,OBSERVATION_TIME ORDER BY FETCHED_AT DESC,DELIVERY_ORDER DESC)=1)
SELECT f.LOGICAL_ID,f.HORIZON,a.VERSION_ID ACTUAL_VERSION,'retrospective_frozen' POLICY,a.VALUE ACTUAL,
 ABS(f.PREDICTION-a.VALUE) ABSOLUTE_ERROR,f.PREDICTION-a.VALUE SIGNED_ERROR,CURRENT_TIMESTAMP() EVALUATED_AT
FROM GRIDCAST_PILOT.ANALYTICS.FORECAST f JOIN actuals a
 ON f.AUTHORITY=a.AUTHORITY AND f.METRIC=a.METRIC AND f.TARGET=a.OBSERVATION_TIME AND f.UNIT=a.UNIT;
MERGE INTO GRIDCAST_PILOT.ANALYTICS.FORECAST_ERROR t USING GRIDCAST_PILOT.ANALYTICS.ERROR_LOAD s
 ON t.LOGICAL_ID=s.LOGICAL_ID AND t.HORIZON=s.HORIZON AND t.ACTUAL_VERSION=s.ACTUAL_VERSION AND t.POLICY=s.POLICY
WHEN NOT MATCHED THEN INSERT ALL BY NAME;
-- Replay this MERGE: count must be unchanged. Changed actual versions create new error vintages.
SELECT COUNT(*),COUNT(DISTINCT LOGICAL_ID||':'||HORIZON||':'||ACTUAL_VERSION||':'||POLICY)
 FROM GRIDCAST_PILOT.ANALYTICS.FORECAST_ERROR;
-- One defined vintage, never average multiple revisions together.
CREATE OR REPLACE VIEW GRIDCAST_PILOT.ANALYTICS.LATEST_ERROR AS
 SELECT e.*,f.ORIGIN,f.TARGET,f.PREDICTION FROM GRIDCAST_PILOT.ANALYTICS.FORECAST_ERROR e
 JOIN GRIDCAST_PILOT.ANALYTICS.FORECAST f USING(LOGICAL_ID,HORIZON)
 QUALIFY ROW_NUMBER() OVER(PARTITION BY LOGICAL_ID,HORIZON,POLICY ORDER BY EVALUATED_AT DESC,ACTUAL_VERSION)=1;
-- 1. Error by horizon; WAPE denominator explicitly zero guarded.
SELECT HORIZON,COUNT(*) PAIRED_TARGETS,AVG(ABSOLUTE_ERROR) MAE_MWH,
 100*SUM(ABSOLUTE_ERROR)/NULLIF(SUM(ABS(ACTUAL)),0) WAPE,AVG(SIGNED_ERROR) SIGNED_BIAS
 FROM GRIDCAST_PILOT.ANALYTICS.LATEST_ERROR GROUP BY HORIZON ORDER BY HORIZON;
-- 2. Fixed local final-training peak threshold, not a warehouse test-derived threshold.
SELECT COUNT(*) PEAK_TARGETS,AVG(ABSOLUTE_ERROR) PEAK_MAE_MWH
 FROM GRIDCAST_PILOT.ANALYTICS.LATEST_ERROR WHERE ACTUAL>=118411.4;
-- 3. Source seasonality. One version per timestamp before aggregating.
SELECT DATE_PART(hour,CONVERT_TIMEZONE('America/New_York',TARGET)) LOCAL_HOUR,
 DAYOFWEEKISO(CONVERT_TIMEZONE('America/New_York',TARGET)) WEEKDAY,COUNT(*) TARGETS,AVG(ACTUAL) MEAN_MWH
 FROM GRIDCAST_PILOT.ANALYTICS.LATEST_ERROR GROUP BY 1,2 ORDER BY 1,2;
-- 4. Source/model health, with fixtures excluded.
SELECT MODE,RELEASE_ID,MODEL_VERSION,COUNT(*) FORECAST_ROWS,COUNT(DISTINCT LOGICAL_ID) BATCHES
 FROM GRIDCAST_PILOT.ANALYTICS.FORECAST GROUP BY 1,2,3;
SELECT MIN(FETCHED_AT),MAX(FETCHED_AT),COUNT(*) DELIVERIES,COUNT(DISTINCT VERSION_ID) VERSIONS
 FROM GRIDCAST_PILOT.RAW.OBSERVATION_RECEIPT;
ALTER WAREHOUSE GRIDCAST_WH SUSPEND;

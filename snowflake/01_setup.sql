-- USER-RUN ONLY. Review role/account balance and replace identifiers if needed.
CREATE DATABASE IF NOT EXISTS GRIDCAST_PILOT;
CREATE SCHEMA IF NOT EXISTS GRIDCAST_PILOT.RAW;
CREATE SCHEMA IF NOT EXISTS GRIDCAST_PILOT.FEATURES;
CREATE SCHEMA IF NOT EXISTS GRIDCAST_PILOT.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS GRIDCAST_PILOT.RAW_FIXTURE;
CREATE WAREHOUSE IF NOT EXISTS GRIDCAST_WH WAREHOUSE_SIZE='XSMALL'
  AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
ALTER WAREHOUSE GRIDCAST_WH SET STATEMENT_TIMEOUT_IN_SECONDS=300;
USE WAREHOUSE GRIDCAST_WH;
ALTER SESSION SET TIMEZONE='UTC',QUERY_TAG='GridCast_manual_pilot',STATEMENT_TIMEOUT_IN_SECONDS=300;
CREATE FILE FORMAT IF NOT EXISTS GRIDCAST_PILOT.RAW.PARQUET_FMT TYPE=PARQUET;
CREATE STAGE IF NOT EXISTS GRIDCAST_PILOT.RAW.INPUT_STAGE FILE_FORMAT=GRIDCAST_PILOT.RAW.PARQUET_FMT;
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.RAW.VERSION_STAGE (PAYLOAD VARIANT);
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.RAW.RECEIPT_STAGE (PAYLOAD VARIANT);
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.RAW.OBSERVATION_VERSION (
 VERSION_ID VARCHAR,AUTHORITY VARCHAR,METRIC VARCHAR,OBSERVATION_TIME TIMESTAMP_TZ,
 RAW_VALUE VARCHAR,VALUE DOUBLE,UNIT VARCHAR,FIRST_SEEN TIMESTAMP_TZ,VALID BOOLEAN,QUALITY VARCHAR);
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.RAW.OBSERVATION_RECEIPT (
 FETCH_ID VARCHAR,VERSION_ID VARCHAR,ARTIFACT_ID VARCHAR,PAGE_OFFSET BIGINT,ROW_NUMBER BIGINT,
 FETCHED_AT TIMESTAMP_TZ,DELIVERY_ORDER BIGINT);
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.RAW_FIXTURE.OBSERVATION_VERSION LIKE GRIDCAST_PILOT.RAW.OBSERVATION_VERSION;
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.RAW_FIXTURE.OBSERVATION_RECEIPT LIKE GRIDCAST_PILOT.RAW.OBSERVATION_RECEIPT;
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.ANALYTICS.RELEASE_METADATA (
 RELEASE_ID VARCHAR,MODEL_CHECKSUM VARCHAR,FEATURE_SCHEMA VARIANT,MODE VARCHAR,CREATED_AT TIMESTAMP_TZ);
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.ANALYTICS.FORECAST (
 LOGICAL_ID VARCHAR,HORIZON INTEGER,ORIGIN TIMESTAMP_TZ,TARGET TIMESTAMP_TZ,AUTHORITY VARCHAR,
 METRIC VARCHAR,UNIT VARCHAR,RELEASE_ID VARCHAR,MODEL_VERSION VARCHAR,PREDICTION DOUBLE,MODE VARCHAR);
CREATE TABLE IF NOT EXISTS GRIDCAST_PILOT.ANALYTICS.FORECAST_ERROR (
 LOGICAL_ID VARCHAR,HORIZON INTEGER,ACTUAL_VERSION VARCHAR,POLICY VARCHAR,ACTUAL DOUBLE,
 ABSOLUTE_ERROR DOUBLE,SIGNED_ERROR DOUBLE,EVALUATED_AT TIMESTAMP_TZ);
SELECT CURRENT_ACCOUNT(),CURRENT_ROLE(),CURRENT_WAREHOUSE(),CURRENT_VERSION();
